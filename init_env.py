CONFIG_FORMAT = """# Autogenerated. Do not edit.
import os
from dataclasses import dataclass

from dotenv import dotenv_values, load_dotenv

load_dotenv()


@dataclass(frozen=True)
class Variable:
    key: str
    value: str


@dataclass(frozen=True)
class Config:
ENV_VARIABLES_PLACEHOLDER


def get_env_or_raise(key: str) -> str:
    value = os.getenv(key)
    if value is None:
        raise ValueError(f"no {key} variable is set")
    return value


def init() -> Config:
    return Config(**{
k: Variable(k, get_env_or_raise(k))
        for k in dotenv_values().keys()
    })


CONFIG: Config = init()

if __name__ == '__main__':
    print("Config is valid!")
"""


def get_dotenv_content(dotenv_path: Path, fmt: str) -> str:
    return fmt.replace("THIS_SCRIPT_ABSOLUTE_PATH", str(dotenv_path))


def get_config_content(dotenv_content: str, fmt: str) -> str:
    dotenv_dict = dotenv_values(stream=StringIO(dotenv_content))
    keys = dotenv_dict.keys()
    variables = "".join([f"    {k}: Variable\n" for k in keys])
    return fmt.replace("ENV_VARIABLES_PLACEHOLDER", variables)


def write(path: Path, content: str):
    with open(path, "w") as f:
        f.write(content)


def main():
    dotenv_abs_dir = Path(os.path.dirname(os.path.realpath(__file__)))
    dotenv_abs_file = dotenv_abs_dir / ".env"
    dotenv_content = get_dotenv_content(dotenv_abs_dir, DOT_ENV_FORMAT)
    write(dotenv_abs_file, dotenv_content)

    config_path = (Path(os.path.dirname(os.path.realpath(__file__)))
                   / "config.py")
    config_content = get_config_content(dotenv_content, CONFIG_FORMAT)
    write(config_path, config_content)


if __name__ == '__main__':
    main()
